#include <iostream>
#include <thread>         // для работы с потоками
#include <chrono>         // для работы со временем (задержки)

using namespace std;

// Глобальная переменная - счётчик клиентов в очереди
// Она будет общей для обоих потоков
int clientCounter = 0;

// Максимальное количество клиентов, которые придут
int maxClients = 10;

/**
 * Функция для первого потока - имитация прихода клиентов
 * Эта функция будет выполняться в отдельном потоке
 */
void clientThread() {
    // Счётчик пришедших клиентов
    int arrivedClients = 0;

    // Цикл работает пока не придут все клиенты
    while (arrivedClients < maxClients) {
        // Задержка 1 секунда (имитация прихода клиента)
        this_thread::sleep_for(chrono::seconds(1));

        // Увеличиваем счётчик клиентов в очереди
        clientCounter++;
        arrivedClients++;

        // Выводим информацию о новом клиенте
        cout << "Пришёл клиент! Клиентов в очереди: " << clientCounter
            << " (всего пришло: " << arrivedClients << ")" << endl;
    }

    cout << "\n>>> Все клиенты пришли! Больше клиентов не будет.\n" << endl;
}

/**
 * Функция для второго потока - имитация работы операциониста
 * Эта функция будет выполняться в отдельном потоке
 */
void operatorThread() {
    // Счётчик обслуженных клиентов
    int servedClients = 0;

    // Операционист работает пока не обслужит всех клиентов
    while (servedClients < maxClients) {
        // Задержка 2 секунды (имитация обслуживания клиента)
        this_thread::sleep_for(chrono::seconds(2));

        // Проверяем, есть ли клиенты в очереди
        if (clientCounter > 0) {
            // Уменьшаем счётчик (обслужили одного клиента)
            clientCounter--;
            servedClients++;

            // Выводим информацию об обслуженном клиенте
            cout << "Операционист обслужил клиента! Осталось в очереди: "
                << clientCounter << " (обслужено: " << servedClients << ")" << endl;
        }
        else {
            // Если очередь пуста, операционист ждёт
            cout << "Операционист ждёт... Очередь пуста." << endl;
        }
    }

    cout << "\n>>> Операционист обслужил всех клиентов! Работа завершена.\n" << endl;
}

/**
 * Главная функция программы
 */
int main() {
    // Устанавливаем русскую локаль для корректного отображения текста
    setlocale(LC_ALL, "Russian");

    cout << "=== Симуляция очереди клиентов ===" << endl;
    cout << "Максимальное количество клиентов: " << maxClients << endl;
    cout << "Клиенты приходят каждую 1 секунду" << endl;
    cout << "Операционист обслуживает каждые 2 секунды" << endl;
    cout << "====================================\n" << endl;

    // Создаём первый поток для клиентов
    // thread - это класс, который создаёт новый поток
    // В скобках указываем функцию, которая будет выполняться в этом потоке
    thread client(clientThread);

    // Создаём второй поток для операциониста
    thread oper(operatorThread);

    // Ждём завершения потока клиентов
    // join() означает "дождаться окончания работы потока"
    // Без этого главная программа завершится раньше, чем потоки закончат работу
    client.join();

    // Ждём завершения потока операциониста
    oper.join();

    cout << "=== Программа завершена ===" << endl;
    cout << "Итоговое значение счётчика: " << clientCounter << endl;

    return 0;
}