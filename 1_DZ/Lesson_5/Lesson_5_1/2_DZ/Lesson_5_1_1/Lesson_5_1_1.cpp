#include <iostream>
using namespace std;

// Определение структуры для представления точки в 2D пространстве
struct point {
	double m_x;  // Координата x
	double m_y;  // Координата y

	// Конструктор для инициализации точки
	point(double x, double y) {
		m_x = x;
		m_y = y;  // ИСПРАВЛЕНО: было "y = y;" вместо "m_y = y;"
	}
};  // ИСПРАВЛЕНО: добавлена точка с запятой после структуры

// Функция для вывода координат точки на экран
void print_point(const point& point_object) {
	std::cout << "x:" << point_object.m_x << ", y: "
		<< point_object.m_y << std::endl;
}

// Главная функция программы
int main()  // ИСПРАВЛЕНО: было "Main()" вместо "main()"
{
	int i;
	// Цикл для создания и вывода 5 точек
	for (i = 0; i < 5; i++) {  // ИСПРАВЛЕНО: убрана лишняя точка с запятой после цикла
		// Создание точки с координатами (i, 2*i)
		point my_point(i, 2 * i);
		// Вывод координат созданной точки
		print_point(my_point);
	}
	return 0;  // Возвращаем 0 для успешного завершения программы
}

// УДАЛЕНО: дублирующее определение функции print_point
